export function pickAttendanceMessage(randomValue = Math.random()) {
  const normalized = Number.isFinite(randomValue)
    ? Math.min(Math.max(randomValue, 0), 0.9999999999999999)
    : 0;
  return attendanceMessages[Math.floor(normalized * attendanceMessages.length)];
}
